//! Glyph widths of the standard 14 fonts (Helvetica, Times, Courier,
//! Symbol, ZapfDingbats and their styles).
//!
//! PDFs may use these fonts without embedding them or listing `/Widths`;
//! the metrics below (from Adobe's AFM files) let text be positioned exactly
//! as the producer intended, for both text extraction and rendering.

/// Which standard font a `/BaseFont` name refers to.
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum Standard {
    Latin(&'static [u16]),
    Courier,
    Symbol,
    ZapfDingbats,
}

/// Recognises standard font names and common aliases (`Arial,Bold`,
/// `TimesNewRomanPSMT`, `CourierNew`…).
pub(crate) fn lookup(base_font: &str) -> Option<Standard> {
    let name = match base_font.split_once('+') {
        Some((tag, rest)) if tag.len() == 6 => rest,
        _ => base_font,
    };
    let n: String = name.chars().filter(|c| c.is_ascii_alphanumeric()).collect::<String>().to_ascii_lowercase();
    let bold = n.contains("bold") || n.contains("black") || n.contains("heavy");
    let italic = n.contains("italic") || n.contains("oblique");
    let pick = |r: &'static [u16], b: &'static [u16], i: &'static [u16], bi: &'static [u16]| {
        Some(Standard::Latin(match (bold, italic) {
            (false, false) => r,
            (true, false) => b,
            (false, true) => i,
            (true, true) => bi,
        }))
    };
    if n.starts_with("courier") {
        Some(Standard::Courier)
    } else if n.starts_with("helvetica") || n.starts_with("arial") {
        pick(&HELVETICA_WIDTHS, &HELVETICA_BOLD_WIDTHS, &HELVETICA_OBLIQUE_WIDTHS, &HELVETICA_BOLDOBLIQUE_WIDTHS)
    } else if n.starts_with("times") {
        pick(&TIMES_ROMAN_WIDTHS, &TIMES_BOLD_WIDTHS, &TIMES_ITALIC_WIDTHS, &TIMES_BOLDITALIC_WIDTHS)
    } else if n == "symbol" {
        Some(Standard::Symbol)
    } else if n.starts_with("zapfdingbats") {
        Some(Standard::ZapfDingbats)
    } else {
        None
    }
}

impl Standard {
    /// Width (in 1/1000 em) of the glyph `name` at `code`.
    pub fn width(self, name: Option<&str>, code: u8) -> Option<f64> {
        let w = match self {
            Standard::Courier => 600,
            Standard::Symbol => SYMBOL_WIDTHS[code as usize],
            Standard::ZapfDingbats => ZAPF_DINGBATS_WIDTHS[code as usize],
            Standard::Latin(widths) => {
                let name = name?;
                let find = |n: &str| LATIN_GLYPHS.binary_search(&n).ok().map(|i| widths[i]);
                // Accented letters missing from the table use their base letter.
                find(name).or_else(|| name.get(..1).filter(|_| name.len() > 1).and_then(find))?
            }
        };
        (w > 0).then_some(w as f64)
    }

    /// Width for codes the table doesn't cover.
    pub fn default_width(self) -> f64 {
        match self {
            Standard::Courier => 600.0,
            _ => 500.0,
        }
    }
}

